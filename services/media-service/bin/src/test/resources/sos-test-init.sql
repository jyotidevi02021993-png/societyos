-- Runtime role for tests: not superuser, not table owner, so RLS applies (like <svc>_app).
CREATE ROLE app LOGIN PASSWORD 'app';
GRANT CONNECT ON DATABASE test TO app;
GRANT USAGE ON SCHEMA public TO app;
ALTER DEFAULT PRIVILEGES FOR ROLE test IN SCHEMA public
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO app;
ALTER DEFAULT PRIVILEGES FOR ROLE test IN SCHEMA public
  GRANT USAGE, SELECT ON SEQUENCES TO app;
ALTER DEFAULT PRIVILEGES FOR ROLE test IN SCHEMA public
  GRANT EXECUTE ON FUNCTIONS TO app;
